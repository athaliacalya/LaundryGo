-- =============================================================================
-- Skema Database Supabase / PostgreSQL untuk LaundryGo
-- =============================================================================

-- 1. TABEL: users
-- Menyimpan kredensial dan hak akses pengguna sistem (admin dan kasir)
CREATE TABLE IF NOT EXISTS users (
    id_user BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50) NOT NULL UNIQUE,
    password TEXT NOT NULL,
    nama_lengkap VARCHAR(100) NOT NULL,
    role VARCHAR(20) NOT NULL CHECK (role IN ('admin', 'kasir')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 2. TABEL: pelanggan
-- Menyimpan data master pelanggan laundry
CREATE TABLE IF NOT EXISTS pelanggan (
    id_pelanggan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_pelanggan VARCHAR(100) NOT NULL,
    no_hp VARCHAR(20) NOT NULL,
    alamat TEXT NOT NULL,
    tgl_daftar DATE NOT NULL DEFAULT CURRENT_DATE,
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 3. TABEL: layanan
-- Menyimpan master paket layanan laundry beserta tarif dan estimasi waktu pengerjaan
CREATE TABLE IF NOT EXISTS layanan (
    id_layanan BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nama_layanan VARCHAR(100) NOT NULL,
    satuan VARCHAR(10) NOT NULL CHECK (satuan IN ('kg', 'pcs', 'm2')),
    harga NUMERIC(12, 0) NOT NULL CHECK (harga >= 0),
    estimasi_hari INT NOT NULL CHECK (estimasi_hari >= 1),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 4. TABEL: transaksi
-- Menyimpan header nota transaksi cucian masuk hingga selesai diambil
CREATE TABLE IF NOT EXISTS transaksi (
    id_transaksi TEXT PRIMARY KEY, -- Format contoh: 'T0001', 'T0002'
    tgl_masuk TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    tgl_selesai DATE NOT NULL,
    id_pelanggan BIGINT NOT NULL REFERENCES pelanggan(id_pelanggan),
    id_user BIGINT NOT NULL REFERENCES users(id_user),
    total_bayar NUMERIC(12, 0) NOT NULL DEFAULT 0 CHECK (total_bayar >= 0),
    status_bayar VARCHAR(10) NOT NULL DEFAULT 'belum' CHECK (status_bayar IN ('belum', 'lunas')),
    status_cucian VARCHAR(20) NOT NULL DEFAULT 'diterima' CHECK (status_cucian IN ('diterima', 'diproses', 'selesai', 'diambil')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 5. TABEL: detail_transaksi
-- Menyimpan rincian item layanan cucian per transaksi
-- Menggunakan ON DELETE CASCADE agar otomatis terhapus jika transaksi dihapus
CREATE TABLE IF NOT EXISTS detail_transaksi (
    id_detail BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaksi TEXT NOT NULL REFERENCES transaksi(id_transaksi) ON DELETE CASCADE,
    id_layanan BIGINT NOT NULL REFERENCES layanan(id_layanan),
    jumlah NUMERIC(8, 2) NOT NULL CHECK (jumlah > 0),
    harga_satuan NUMERIC(12, 0) NOT NULL CHECK (harga_satuan >= 0),
    subtotal NUMERIC(12, 0) NOT NULL CHECK (subtotal >= 0),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- 6. TABEL: pembayaran
-- Menyimpan riwayat pembayaran (DP / pelunasan)
-- Relasi ke transaksi tanpa CASCADE agar riwayat transaksi/pembayaran tidak hilang sembarangan
CREATE TABLE IF NOT EXISTS pembayaran (
    id_pembayaran BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_transaksi TEXT NOT NULL REFERENCES transaksi(id_transaksi),
    tgl_bayar TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    jumlah_bayar NUMERIC(12, 0) NOT NULL CHECK (jumlah_bayar > 0),
    metode VARCHAR(20) NOT NULL CHECK (metode IN ('tunai', 'transfer', 'qris')),
    created_at TIMESTAMPTZ DEFAULT NOW()
);

-- =============================================================================
-- ROW LEVEL SECURITY (RLS)
-- =============================================================================
-- Aktifkan RLS untuk semua tabel tanpa policy publik.
-- Seluruh akses data hanya melalui service_role Supabase dari server (API Routes / Server Actions).
ALTER TABLE users ENABLE ROW LEVEL SECURITY;
ALTER TABLE pelanggan ENABLE ROW LEVEL SECURITY;
ALTER TABLE layanan ENABLE ROW LEVEL SECURITY;
ALTER TABLE transaksi ENABLE ROW LEVEL SECURITY;
ALTER TABLE detail_transaksi ENABLE ROW LEVEL SECURITY;
ALTER TABLE pembayaran ENABLE ROW LEVEL SECURITY;

